//! The lrpar plumbing: feeding the hand-written lexer's rich tokens into
//! the generated LALR tables via index-coded lexemes, the `%parse-param`
//! context grammar actions use, and the expected-token oracle that
//! replaces happy's `%error.expected`.

use std::cell::RefCell;
use std::sync::LazyLock;

use cfgrammar::Span as GSpan;
use cfgrammar::yacc::YaccGrammar;
use lrlex::{DefaultLexeme, DefaultLexerTypes, LRLexError};
use lrpar::{Lexeme, Lexer, LexParseError, NonStreamingLexer};
use lrtable::{Minimiser, StIdx, StateTable, from_yacc};

use crate::cst::{CstDecl, CstExpr, CstModule, Separated, Wrapped};
use crate::diag::Diagnostic;
use crate::lexer::token::{Operator, Token, TokenKind};
use crate::maxim_panic;
use crate::parser::support;

/// Token-id constants generated by build.rs from the compiled grammar,
/// so the lexer and the tables can never drift apart.
pub mod token_ids {
    include!(concat!(env!("OUT_DIR"), "/maxim_token_ids.rs"));
}

lrpar::lrpar_mod!("maxim.y");

/// The merged start rule's result: which entry point produced what.
pub enum EntryOut {
    Module(CstModule),
    Decl(CstDecl),
}

/// Which entry point to parse with (happy's `pModule` / `pDeclSeg`).
#[derive(Clone, Copy)]
pub enum ParseMode {
    Module,
    DeclSeg,
}

/// The `%parse-param` context: grammar actions pull rich tokens out of
/// `toks` by lexeme index, and cover-grammar validation errors are
/// recorded here (grmtools actions cannot abort the parse the way
/// happy's monadic actions could — the first recorded error wins and
/// the parse result is discarded).
pub struct ParseCtx<'a> {
    toks: &'a [Token],
    cover_err: RefCell<Option<Diagnostic>>,
}

impl ParseCtx<'_> {
    /// The rich token behind a terminal's lexeme. Lexeme spans index the
    /// token slice, offset by 1 for the synthetic mode token.
    pub fn t(&self, lx: Result<DefaultLexeme<u32>, DefaultLexeme<u32>>) -> Token {
        let lx = lx.expect("RecoveryKind::None never inserts lexemes");
        self.toks[lx.span().start() - 1].clone()
    }

    fn record(&self, d: Diagnostic) {
        let mut slot = self.cover_err.borrow_mut();
        if slot.is_none() {
            *slot = Some(d);
        }
    }

    /// `( … ) => body` — record the rewrite hint; the returned expression
    /// is poison (the recorded error discards the tree).
    pub fn arrow_lambda_error(&self, arrow: &Token) -> CstExpr {
        self.record(support::arrow_lambda_error(arrow));
        CstExpr::Hole(arrow.clone())
    }

    /// Validate cover parens into a group, recording E1102/E1103/E1104
    /// and returning poison on failure.
    pub fn validate_group(&self, w: Wrapped<Option<Separated<CstExpr>>>) -> CstExpr {
        let poison = w.open.clone();
        match support::validate_group(w) {
            Ok(e) => e,
            Err(d) => {
                self.record(d);
                CstExpr::Hole(poison)
            }
        }
    }
}

/// A pre-lexed token stream exposed to lrpar. Lexeme spans are indices
/// into the token vector (offset by one for the mode token), not byte
/// offsets; `span_str`/`line_col` are never consulted because all error
/// prose is built from the rich tokens.
struct TokenLexer {
    lexemes: Vec<DefaultLexeme<u32>>,
}

impl TokenLexer {
    fn new(mode_id: u32, toks: &[Token]) -> TokenLexer {
        let mut lexemes = Vec::with_capacity(toks.len() + 1);
        lexemes.push(DefaultLexeme::new(mode_id, 0, 1));
        for (i, t) in toks.iter().enumerate() {
            lexemes.push(DefaultLexeme::new(tok_id(&t.kind), i + 1, 1));
        }
        TokenLexer { lexemes }
    }
}

impl Lexer<DefaultLexerTypes<u32>> for TokenLexer {
    fn iter<'a>(
        &'a self,
    ) -> Box<dyn Iterator<Item = Result<DefaultLexeme<u32>, LRLexError>> + 'a> {
        Box::new(self.lexemes.iter().map(|&l| Ok(l)))
    }
}

impl<'input> NonStreamingLexer<'input, DefaultLexerTypes<u32>> for TokenLexer {
    fn span_str(&self, _span: GSpan) -> &'input str {
        ""
    }

    fn span_lines_str(&self, _span: GSpan) -> &'input str {
        ""
    }

    fn line_col(&self, _span: GSpan) -> ((usize, usize), (usize, usize)) {
        ((1, 1), (1, 1))
    }
}

/// The grammar's terminal id for a token kind — total, so adding a token
/// kind breaks compilation until it is mapped.
fn tok_id(k: &TokenKind) -> u32 {
    use token_ids::*;
    match k {
        TokenKind::Lower(_) => T_LOWER,
        TokenKind::Upper(_) => T_UPPER,
        TokenKind::Hole => T_HOLE,
        TokenKind::Int(_) => T_INT,
        TokenKind::Float(_) => T_FLOAT,
        TokenKind::Str(_) => T_STRING,
        TokenKind::StringBegin(_) => T_STRINGBEGIN,
        TokenKind::StringMid(_) => T_STRINGMID,
        TokenKind::StringEnd(_) => T_STRINGEND,
        TokenKind::JsxTagStart(_) => T_JSXTAGSTART,
        TokenKind::JsxClose(_) => T_JSXCLOSE,
        TokenKind::JsxTagEnd => T_JSXTAGEND,
        TokenKind::JsxSelfClose => T_JSXSELFCLOSE,
        TokenKind::JsxAttrName(_) => T_JSXATTRNAME,
        TokenKind::JsxText(_) => T_JSXTEXT,
        TokenKind::DollarBrace => T_DOLLARBRACE,
        TokenKind::Module => T_MODULE,
        TokenKind::Import => T_IMPORT,
        TokenKind::Type => T_TYPE,
        TokenKind::Fn => T_FN,
        TokenKind::Cast => T_CAST,
        TokenKind::Component => T_COMPONENT,
        TokenKind::Let => T_LET,
        TokenKind::Match => T_MATCH,
        TokenKind::If => T_IF,
        TokenKind::Else => T_ELSE,
        TokenKind::LParen => T_LPAREN,
        TokenKind::LParenBOL => T_LPARENBOL,
        TokenKind::RParen => T_RPAREN,
        TokenKind::LBrace => T_LBRACE,
        TokenKind::RBrace => T_RBRACE,
        TokenKind::LBracket => T_LBRACKET,
        TokenKind::RBracket => T_RBRACKET,
        TokenKind::Comma => T_COMMA,
        TokenKind::Colon => T_COLON,
        TokenKind::ColonColon => T_COLONCOLON,
        TokenKind::Dot => T_DOT,
        TokenKind::DotDot => T_DOTDOT,
        TokenKind::Eq => T_EQ,
        TokenKind::Bar => T_BAR,
        TokenKind::Bang => T_BANG,
        TokenKind::Arrow => T_ARROW,
        TokenKind::FatArrow => T_FATARROW,
        TokenKind::Pipeline => T_PIPELINE,
        TokenKind::Question => T_QUESTION,
        TokenKind::Lt => T_LT,
        TokenKind::Gt => T_GT,
        TokenKind::Op(op) => match op {
            Operator::Add => T_ADD,
            Operator::Sub => T_SUB,
            Operator::Mul => T_MUL,
            Operator::Div => T_DIV,
            Operator::IntDiv => T_INTDIV,
            Operator::Mod => T_MOD,
            Operator::Pow => T_POW,
            Operator::Concat => T_CONCAT,
            Operator::Eq => T_EQEQ,
            Operator::Neq => T_NEQ,
            Operator::Le => T_LE,
            Operator::Ge => T_GE,
            Operator::And => T_AND,
            Operator::Or => T_OR,
        },
        TokenKind::Eof => T_EOF,
    }
}

/// The independently-built grammar + state table used as the
/// expected-token oracle. `from_yacc(…, Minimiser::Pager)` is the exact
/// call lrpar's compile-time builder makes, so state indices agree with
/// `ParseError::stidx()` from the generated parser (both are built from
/// the same grammar text by the same pinned crate versions).
static TABLES: LazyLock<(YaccGrammar<u32>, StateTable<u32>)> = LazyLock::new(|| {
    let grm: YaccGrammar<u32> = str::parse(include_str!("../maxim.y")).expect("maxim.y parses");
    let (_, stable) = from_yacc(&grm, Minimiser::Pager).expect("maxim.y builds");
    (grm, stable)
});

/// Names of every terminal with a non-error action in the given state —
/// what happy's `%error.expected` handed to `parseError`.
fn expected_token_names(stidx: StIdx<u32>) -> Vec<&'static str> {
    let (grm, stable) = &*TABLES;
    stable
        .state_actions(stidx)
        .filter(|tidx| *tidx != grm.eof_token_idx())
        .filter_map(|tidx| grm.token_name(tidx))
        .collect()
}

/// Parse a token stream (which must end with an `Eof` token) with the
/// given entry point.
pub fn run_parse(toks: &[Token], mode: ParseMode) -> Result<EntryOut, Diagnostic> {
    let mode_id = match mode {
        ParseMode::Module => token_ids::T_MODE_MODULE,
        ParseMode::DeclSeg => token_ids::T_MODE_DECLSEG,
    };
    let lexer = TokenLexer::new(mode_id, toks);
    let ctx = ParseCtx {
        toks,
        cover_err: RefCell::new(None),
    };
    let (res, errs) = maxim_y::parse(&lexer, &ctx);
    // A recorded cover-grammar error always precedes any later parse
    // error in the token stream (reductions run left to right), so it
    // wins — exactly happy's first-Left-aborts behavior.
    if let Some(d) = ctx.cover_err.into_inner() {
        return Err(d);
    }
    if let Some(e) = errs.first() {
        return Err(match e {
            LexParseError::ParseError(pe) => {
                let idx = pe.lexeme().span().start();
                let stuck = if idx == 0 {
                    maxim_panic!("parse error on the synthetic mode token")
                } else {
                    &toks[idx - 1]
                };
                support::parse_error(stuck, &expected_token_names(pe.stidx()))
            }
            LexParseError::LexError(_) => {
                maxim_panic!("token lexer produced a lex error (it never does)")
            }
        });
    }
    match res {
        Some(out) => Ok(out),
        None => maxim_panic!("parse returned neither a value nor an error"),
    }
}
