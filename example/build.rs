//! Build script: compile the yacc grammar with grmtools and emit a Rust
//! constants module mapping token names to the ids the generated parser
//! expects (the analogue of happy's `%token` block staying in sync with
//! the lexer by construction).

use std::collections::HashMap;
use std::env;
use std::error::Error;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use lrlex::DefaultLexerTypes;
use lrpar::CTParserBuilder;

fn main() -> Result<(), Box<dyn Error>> {
    let ctp = CTParserBuilder::<DefaultLexerTypes<u32>>::new()
        .grammar_in_src_dir("maxim.y")?
        .build()?;
    write_token_consts("maxim_token_ids.rs", ctp.token_map())?;
    Ok(())
}

/// Emit `pub const T_<NAME>: u32 = <id>;` for every terminal, so the
/// hand-written lexer and the generated tables can never drift apart.
fn write_token_consts(
    file_name: &str,
    token_map: &HashMap<String, u32>,
) -> Result<(), Box<dyn Error>> {
    let mut entries: Vec<(&String, &u32)> = token_map.iter().collect();
    entries.sort();
    let mut out = String::new();
    writeln!(out, "// Generated by build.rs — do not edit.")?;
    for (name, id) in entries {
        writeln!(out, "pub const T_{}: u32 = {};", const_ident(name), id)?;
    }
    let out_dir = env::var("OUT_DIR")?;
    fs::write(Path::new(&out_dir).join(file_name), out)?;
    Ok(())
}

/// Turn a grammar token name into a Rust const identifier suffix.
fn const_ident(name: &str) -> String {
    let named = match name {
        "(" => "LPAREN",
        ")" => "RPAREN",
        "{" => "LBRACE",
        "}" => "RBRACE",
        "[" => "LBRACKET",
        "]" => "RBRACKET",
        "," => "COMMA",
        ":" => "COLON",
        "." => "DOT",
        ".." => "DOTDOT",
        "=" => "EQ",
        "|" => "BAR",
        "!" => "BANG",
        "->" => "ARROW",
        "=>" => "FATARROW",
        "|>" => "PIPELINE",
        "?" => "QUESTION",
        "::" => "COLONCOLON",
        "<" => "LT",
        ">" => "GT",
        "+" => "ADD",
        "-" => "SUB",
        "*" => "MUL",
        "/" => "DIV",
        "~/" => "INTDIV",
        "%" => "MOD",
        "**" => "POW",
        "++" => "CONCAT",
        "==" => "EQEQ",
        "!=" => "NEQ",
        "<=" => "LE",
        ">=" => "GE",
        "&&" => "AND",
        "||" => "OR",
        other => {
            return other
                .chars()
                .map(|c| {
                    if c.is_ascii_alphanumeric() || c == '_' {
                        c.to_ascii_uppercase()
                    } else {
                        '_'
                    }
                })
                .collect();
        }
    };
    named.to_string()
}
