/// Samples for one start rule of the syntactic grammar.
pub struct SyntaxSamples {
    pub section: &'static str,
    pub start: &'static str,
    pub accept: &'static [&'static str],
    pub reject: &'static [&'static str],
    /// Valid samples and how they must group: `⟨a + ⟨b * c⟩⟩`.
    pub grouped: &'static [(&'static str, &'static str)],
}

